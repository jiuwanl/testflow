-- Run finalization and event insertion share the existing MySQL transaction.
CREATE TABLE tf_outbox_event (
 event_id CHAR(36) PRIMARY KEY,
 run_id BIGINT NOT NULL,
 project_id BIGINT NOT NULL,
 event_type VARCHAR(32) NOT NULL DEFAULT 'RUN_FINALIZED',
 schema_version INT NOT NULL DEFAULT 1,
 payload JSON NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
 attempt_count INT NOT NULL DEFAULT 0,
 next_attempt_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 claim_token CHAR(36) NULL,
 lease_until DATETIME(3) NULL,
 published_at DATETIME(3) NULL,
 last_error_code VARCHAR(40) NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE KEY uk_outbox_run_type(run_id,event_type),
 KEY ix_outbox_dispatch(status,next_attempt_at,lease_until),
 KEY ix_outbox_project(project_id,status,created_at),
 CONSTRAINT fk_outbox_run FOREIGN KEY(run_id) REFERENCES tf_test_run(id),
 CONSTRAINT ck_outbox_status CHECK(status IN ('PENDING','PUBLISHING','PUBLISHED'))
);
CREATE TABLE tf_quality_run_fact (
 run_id BIGINT PRIMARY KEY,
 event_id CHAR(36) NOT NULL,
 project_id BIGINT NOT NULL,
 kind VARCHAR(8) NOT NULL,
 source_id BIGINT NOT NULL,
 env_id BIGINT NOT NULL,
 finished_at DATETIME(3) NOT NULL,
 state VARCHAR(16) NOT NULL,
 outcome VARCHAR(16) NOT NULL,
 total_count INT NOT NULL,
 passed_count INT NOT NULL,
 failed_count INT NOT NULL,
 error_count INT NOT NULL,
 skipped_count INT NOT NULL,
 cancelled_count INT NOT NULL,
 unknown_count INT NOT NULL,
 duration_ms BIGINT NULL,
 payload_hash CHAR(64) NOT NULL,
 projected_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE KEY uk_quality_event(event_id),
 KEY ix_quality_trend(project_id,kind,source_id,env_id,finished_at),
 KEY ix_quality_time(project_id,finished_at,run_id),
 CONSTRAINT fk_quality_run FOREIGN KEY(run_id) REFERENCES tf_test_run(id),
 CONSTRAINT fk_quality_event FOREIGN KEY(event_id) REFERENCES tf_outbox_event(event_id),
 CONSTRAINT ck_quality_counts CHECK(total_count>0 AND passed_count>=0 AND failed_count>=0 AND error_count>=0 AND skipped_count>=0 AND cancelled_count>=0 AND unknown_count>=0 AND total_count=passed_count+failed_count+error_count+skipped_count+cancelled_count+unknown_count),
 CONSTRAINT ck_quality_state CHECK(state IN ('COMPLETED','CANCELLED','TIMED_OUT','INTERRUPTED'))
);
-- A bounded-retry consumer parks diagnostics here, without retaining untrusted raw message bodies.
CREATE TABLE tf_quality_failure (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 topic VARCHAR(249) NOT NULL,
 partition_id INT NOT NULL,
 record_offset BIGINT NOT NULL,
 event_id CHAR(36) NULL,
 project_id BIGINT NULL,
 payload_hash CHAR(64) NOT NULL,
 error_code VARCHAR(40) NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'OPEN',
 replay_count INT NOT NULL DEFAULT 0,
 first_seen_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 last_seen_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE KEY uk_quality_failure_record(topic,partition_id,record_offset),
 KEY ix_quality_failure_project(project_id,status,id),
 KEY ix_quality_failure_event(event_id,status),
 CONSTRAINT ck_quality_failure_status CHECK(status IN ('OPEN','REPLAY_REQUESTED','RESOLVED'))
);
